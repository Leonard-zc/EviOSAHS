def common_runtime_arguments(input_pkl: str, image_dir: str, qwen_root: str | None = None) -> list[str]:
    arguments = [
        "--input-pkl",
        input_pkl,
        "--image-dir",
        image_dir,
    ]
    if qwen_root:
        arguments.extend(
            [
                "--qwen-vl-model-path",
                str(Path(qwen_root) / "Qwen2.5-VL-7B-Instruct"),
                "--qwen-text-model-path",
                str(Path(qwen_root) / "Qwen2.5-7B-Instruct"),
            ]
        )
    return arguments
